/**
 * Creates two isolated test accounts in the DEVELOPMENT Clerk instance.
 *
 *   node scripts/create-test-users.mjs
 *
 * These exist so the signed-in account-switch case can be tested in a
 * browser: proving that account B never sees account A's saved diagnostic
 * state needs two real sessions, which no amount of unit testing
 * substitutes for.
 *
 * REFUSES to run against a production instance. Test accounts belong in
 * the development instance, and production accounts are not created
 * without explicit authorization.
 *
 * Passwords are generated here and written to `.env.test.local`
 * (gitignored by the `.env.*.local` rule). They are never printed.
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { randomBytes } from "node:crypto";

const env = {};
for (const file of [".env.local", ".env"]) {
  try {
    for (const line of readFileSync(file, "utf8").split("\n")) {
      const m = line.match(/^([A-Z_0-9]+)=["']?([^"'\n]*)["']?$/);
      if (m && !env[m[1]]) env[m[1]] = m[2];
    }
  } catch {}
}

const key = env.CLERK_SECRET_KEY;
if (!key) {
  console.error("CLERK_SECRET_KEY not found in .env.local");
  process.exit(1);
}
if (key.startsWith("sk_live")) {
  console.error(
    "Refusing: that is a PRODUCTION key. Test accounts are created in the development instance only."
  );
  process.exit(1);
}
console.log("instance: development (sk_test)");

const api = async (path, init) => {
  const res = await fetch(`https://api.clerk.com/v1${path}`, {
    ...init,
    headers: { Authorization: `Bearer ${key}`, "Content-Type": "application/json", ...init?.headers },
  });
  const body = await res.json().catch(() => ({}));
  if (!res.ok) throw new Error(`${path} -> ${res.status} ${JSON.stringify(body).slice(0, 300)}`);
  return body;
};

// This instance requires a username as well as an email, so both are
// supplied rather than discovered at failure time.
const accounts = [
  { label: "A", email: "modus-test-a@playwright-qa.dev", username: "modus_test_a" },
  { label: "B", email: "modus-test-b@playwright-qa.dev", username: "modus_test_b" },
];

const lines = ["# Isolated Clerk test accounts (development instance only).",
               "# Generated by scripts/create-test-users.mjs. Never commit this file."];

for (const account of accounts) {
  const existing = await api(`/users?email_address=${encodeURIComponent(account.email)}`);
  let user = Array.isArray(existing) ? existing[0] : null;
  const password = randomBytes(18).toString("base64url");

  if (user) {
    await api(`/users/${user.id}`, { method: "PATCH", body: JSON.stringify({ password }) });
    console.log(`account ${account.label}: reused ${user.id}, password rotated`);
  } else {
    user = await api("/users", {
      method: "POST",
      body: JSON.stringify({
        email_address: [account.email],
        username: account.username,
        password,
        skip_password_checks: false,
      }),
    });
    console.log(`account ${account.label}: created ${user.id}`);
  }
  lines.push(`MODUS_TEST_${account.label}_EMAIL=${account.email}`);
  lines.push(`MODUS_TEST_${account.label}_USERNAME=${account.username}`);
  lines.push(`MODUS_TEST_${account.label}_PASSWORD=${password}`);
  lines.push(`MODUS_TEST_${account.label}_USER_ID=${user.id}`);
}

writeFileSync(".env.test.local", lines.join("\n") + "\n");
console.log(`\nCredentials written to .env.test.local (gitignored). Not printed here.`);
console.log(existsSync(".env.test.local") ? "ready" : "WRITE FAILED");
